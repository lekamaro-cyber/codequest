import math
print(math.sqrt(16), math.floor(-2.5), math.ceil(2.1), math.pi)
print(math.factorial(20), math.gcd(12, 18), math.lcm(4, 6))
print(math.isclose(0.1 + 0.2, 0.3), math.hypot(3, 4), math.trunc(-3.7))
print(round(math.log(100, 10), 6), math.log2(8), math.log10(1000), math.exp(0))
print(math.isqrt(17), math.comb(5, 2), math.perm(5, 2), math.prod([1, 2, 3, 4]))
print(math.inf > 10**100, -math.inf, math.degrees(math.pi))
